def _stable_index(key):
    """同一个 key 永远得到同一个下标（crc32 跨平台稳定）。"""
    return zlib.crc32(str(key).encode("utf-8"))


def hint_for(key):
    """按 key 稳定选一条提醒句；未知标签用通用模板并带上标签名。"""
    alternatives = KNOWN_HINTS.get(key)
    if alternatives is None:
        template = GENERIC_HINTS[_stable_index(key) % len(GENERIC_HINTS)]
        return template.format(name=key)
    return alternatives[_stable_index(key) % len(alternatives)]


def checklist():
    return list(CHECKLIST)
